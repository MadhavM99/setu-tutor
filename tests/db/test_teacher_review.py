"""Teacher console I: native review of script, word, chunk and scene content (slice 4.1; X-TCH-01, gate G3).

Every approval is one teacher's, declared as a native Telugu speaker, of the exact version shown; two different
reviewers make content visible to learners; every decision is kept in `content_review` and the ledger."""
