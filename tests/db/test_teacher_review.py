from sqlalchemy import text
from sqlalchemy.exc import DBAPIError

from setu.content import letters as L

from .helpers import approvals
from .test_letters import PASS, client

LETTER = "te-letter:అ"


def teacher(engine):
    from setu.web import auth
    from setu.web.app import create_app

    c = TestClient(create_app(engine=engine), base_url="https://testserver")
    r = c.post("/api/auth/register", json={"invite_code": auth.create_invite(engine, role="teacher"), "passphrase": PASS})
    return c, r.json()["learner_id"]


def one(engine, sql, **p):
    with engine.connect() as c:
        return c.execute(text(sql), p).first()


